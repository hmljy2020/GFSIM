#!/usr/bin/env python3
"""Emit the fixed mesh wiring and one reusable MeshNode and its top-level instances."""
import argparse
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent
COLUMNS, ROWS = 8, 5
STEPS = (("West", -1, 0), ("East", 1, 0), ("North", 0, -1), ("South", 0, 1))
BANNER = "// Generated by examples/mesh/generate_mesh.py.\n"


def render(template, **values):
    return Template((ROOT / "codegen" / template).read_text()).substitute(values)


def neighbors(node):
    x, y = node % COLUMNS, node // COLUMNS
    for direction, dx, dy in STEPS:
        nx, ny = x + dx, y + dy
        if 0 <= nx < COLUMNS and 0 <= ny < ROWS:
            yield direction, ny * COLUMNS + nx


def output_block(directions, out):
    ports = [d.lower() for d in directions]
    requests = ", ".join(f"{p}Request" for p in ports)
    port = out.lower()
    winner = f"{port}Grant"
    lines = [
        f"    const auto {winner} = Grant(Direction::{out}, last{out}_, {requests});",
        f"    if ({winner} != Direction::None && {port}Out_ && !{port}Out_->Full()) {{",
        "        std::shared_ptr<Packet> packet;",
        f"        switch ({winner}) {{",
    ]
    for direction in directions:
        src = direction.lower()
        lines.extend([f"        case Direction::{direction}:",
                      f"            packet = {src}In_->Front();",
                      f"            {port}Out_->Write(packet);",
                      f"            {src}In_->Pop();",
                      "            break;"])
    lines.extend(['        default: GFSIM_ASSERT(false) << "invalid grant";',
                  "        }"])
    if out != "Local":
        lines.extend(["        ++packet->hops;", "        ++forwarded_;"])
    lines.extend([f"        last{out}_ = {winner};",
                  "        GetSim()->MarkProgress();",
                  f"        LogTransfer(packet->id, {port}Out_->Name());",
                  f"    }} else if ({winner} != Direction::None && {port}Out_ && Log().Level() == gfsim::LogLevel::Debug) {{",
                  f'        Log().Debug(Name(), "blocked") << {port}Out_->Name();',
                  "    }"])
    return "\n".join(lines)


def router_files():
    name = "MeshNode"
    directions = ["Local", "West", "East", "North", "South"]
    ports = [d.lower() for d in directions]
    parameters = ",\n".join(f"        gfsim::SimQueue<Packet>* {p}In, gfsim::SimQueue<Packet>* {p}Out"
                             for p in ports)
    requests = "        " + ", ".join(f"Direction {p}" for p in ports)
    members = "\n\n".join(
        f"    INPUT gfsim::SimQueue<Packet>* {p}In_;\n    OUTPUT gfsim::SimQueue<Packet>* {p}Out_;\n"
        f"    Direction last{d}_ = Direction::None;"
        for d, p in zip(directions, ports))
    header = render("MeshRouter.h.in", name=name, parameters=parameters,
                    requests=requests, members=members)
    source = render(
        "MeshRouter.cpp.in", name=name, parameters=parameters, requests=requests,
        bindings=",\n".join(f"      {p}In_({p}In ? BindInput({p}In) : nullptr), {p}Out_({p}Out ? BindOutput({p}Out) : nullptr)"
                            for p in ports),
        after_last="\n".join(f"    if (last < Direction::{d} && {p} == output) return Direction::{d};"
                             for d, p in zip(directions, ports)),
        after_wrap="\n".join(f"    if ({p} == output) return Direction::{d};"
                             for d, p in zip(directions, ports)),
        read_inputs="\n".join(f"    const auto {p}Request = (!{p}In_ || {p}In_->Empty()) ? Direction::None"
                              f" : Route(id_, {p}In_->Peek().destination);" for p in ports),
        output_blocks="\n\n".join(output_block(directions, d) for d in directions),
        reset="\n".join(f"    last{d}_ = Direction::None;" for d in directions))
    stem = name
    return {stem + ".h": BANNER + header, stem + ".cpp": BANNER + source}


def mesh_files():
    ids = range(COLUMNS * ROWS)
    files = router_files()
    queues, nodes, ports = [], [], []
    for node in ids:
        inputs_outputs = [f"/* Local in, out */ inject{node}_, deliver{node}_"]
        connected = dict(neighbors(node))
        for direction, _, _ in STEPS:
            if direction in connected:
                peer = connected[direction]
                inputs_outputs.append(f"/* {direction} in, out */ link_{peer}_to_{node}, link_{node}_to_{peer}")
            else:
                inputs_outputs.append(f"/* {direction} boundary */ nullptr, nullptr")
        ports.append(f"    OUTPUT gfsim::SimQueue<Packet>* inject{node}_ = nullptr;\n"
                     f"    INPUT gfsim::SimQueue<Packet>* deliver{node}_ = nullptr;")
        queues.extend([f'    inject{node}_ = BindOutput(MakeQueue("inject_{node}"));',
                       f'    deliver{node}_ = BindInput(MakeQueue("deliver_{node}"));'])
        for direction, peer in neighbors(node):
            incoming, outgoing = f"link_{peer}_to_{node}", f"link_{node}_to_{peer}"
            if node < peer:
                for link in (outgoing, incoming):
                    queues.append(f'    auto* {link} = MakeQueue("{link}");')
        arguments = ",\n            ".join(inputs_outputs)
        nodes.append(f"        std::make_shared<MeshNode>({node},\n            {arguments})")

    files["generated/MeshDimensions.h"] = BANNER + f"""#pragma once

namespace mesh_example {{
constexpr int kColumns = {COLUMNS};
constexpr int kRows = {ROWS};
constexpr int kNodes = kColumns * kRows;
constexpr int kPackets = kNodes * (kNodes - 1);
}} // namespace mesh_example
"""
    files["MeshBench.h"] = BANNER + render("MeshBench.h.in", ports="\n".join(ports))
    files["MeshBench.cpp"] = BANNER + render(
        "MeshBench.cpp.in", object_count=len(queues) + len(ids), queues="\n".join(queues),
        nodes=",\n".join(nodes), includes='#include "MeshNode.h"',
        inject_calls="\n".join(f"    Inject({i}, *inject{i}_);" for i in ids),
        check_calls="\n".join(f"    Check({i}, *deliver{i}_);" for i in ids))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in generated files")
    args = parser.parse_args()
    stale = []
    for relative, content in mesh_files().items():
        path = ROOT / relative
        if path.is_file() and path.read_bytes() == content.encode("utf-8"):
            continue
        if args.check:
            stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    if stale:
        parser.exit(1, "Regenerate mesh sources: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
